import assert from 'node:assert/strict';
import {due,addMonths,validateRules} from './domain.mjs';
const car={id:'v',km:11000};const r={id:'r',vehicleId:'v',km:10000,months:6,baseKm:0,baseDate:'2026-01-31'};
assert.equal(addMonths('2024-01-31',1),'2024-02-29');
assert.equal(addMonths('2026-08-31',6),'2027-02-28');
assert.equal(due(r,car,[],'2026-04-01').status,'late');
assert.equal(due(r,{...car,km:100},[],'2026-08-01').status,'late');
assert.equal(due(r,{...car,km:9500},[],'2026-04-01').status,'soon');
assert.equal(due({...r,baseKm:null,baseDate:''},car,[],'2026-04-01').status,'unknown');
assert.equal(due({...r,baseDate:''},{...car,km:100},[],'2026-04-01').status,'unknown');
assert.equal(due({...r,baseDate:''},car,[],'2026-04-01').status,'late');
const records=[{vehicleId:'v',ruleId:'r',date:'2026-04-01',km:11000},{vehicleId:'v',ruleId:'other',date:'2026-05-01',km:15000}];
const d=due(r,car,records,'2026-04-01');assert.equal(d.km,21000);assert.equal(d.date,'2026-10-01');assert.equal(d.status,'good');
assert.throws(()=>validateRules([{name:'x',km:-1,months:1}]));
assert.throws(()=>validateRules([{name:'x',km:0,months:0}]));
assert.throws(()=>validateRules([{name:'x',months:1.5}]));
assert.throws(()=>validateRules([{name:'x',months:6,once:true}]));
assert.equal(validateRules([{name:'x',km:1000}])[0].baseKm,null);
console.log('14 domain assertions passed');
