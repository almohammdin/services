import {test,expect} from 'vitest';
import {render,screen,within,waitFor,cleanup} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from '../src/App';
import {loadState} from '../src/storage';
test('simple entry creates a plan, saves a meeting and restores the participation',async()=>{
 const user=userEvent.setup();const first=render(<App/>);
 await user.click(await screen.findByRole('button',{name:'زائر أزور المعرض أو أحضر المؤتمر'}));
 const form=within(screen.getByRole('dialog'));
 await user.type(form.getByLabelText('اسم الفعالية'),'معرض تجربة المنصة');
 await user.click(form.getByRole('radio',{name:/البحث عن موردين/}));
 await user.click(form.getByRole('button',{name:'عرض خطتي'}));
 await screen.findByRole('heading',{name:'خطة مشاركتك'});
 expect(screen.getAllByRole('checkbox')).toHaveLength(3);
 await user.click(screen.getAllByRole('checkbox')[0]);
 await user.click(screen.getByRole('button',{name:'أضف أول مورد'}));
 const contact=within(screen.getByRole('dialog'));
 await user.type(contact.getByLabelText('الجهة أو الشخص'),'مورد التجربة');
 await user.type(contact.getByLabelText('أهم ما دار في اللقاء'),'مراجعة معدات الصيانة');
 await user.click(contact.getByRole('button',{name:'حفظ اللقاء'}));
 await waitFor(async()=>{const saved=await loadState();expect(saved.state.events[0].name).toBe('معرض تجربة المنصة');expect(saved.state.contacts[0].company).toBe('مورد التجربة');expect(saved.state.tasks).toHaveLength(7);expect(saved.state.tasks[0].done).toBe(true);});
 first.unmount();render(<App/>);expect(await screen.findByText('تمت استعادة مشاركاتك')).toBeTruthy();
 expect(await screen.findByRole('heading',{name:'معرض تجربة المنصة'})).toBeTruthy();
 expect((screen.getAllByRole('checkbox')[0] as HTMLInputElement).checked).toBe(true);cleanup();
});
