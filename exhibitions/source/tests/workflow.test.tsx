import {test,expect} from 'vitest';
import {render,screen,within,waitFor,cleanup} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from '../src/App';
import {loadState} from '../src/storage';
test('participation, follow-up, scheduling, results and persistence work together',async()=>{
 const user=userEvent.setup();const first=render(<App/>);
 await screen.findByRole('button',{name:/ابدأ مشاركتك/});
 await user.click(screen.getByRole('button',{name:/ابدأ مشاركتك/}));
 const form=within(screen.getByRole('dialog'));
 await user.type(form.getByLabelText('اسم الفعالية'),'معرض تجربة المنصة');
 await user.type(form.getByLabelText(/النتيجة التي تريد الوصول لها/),'مقارنة 3 عروض معدات');
 await user.click(form.getByRole('button',{name:'إنشاء المشاركة'}));
 await screen.findByText('مقارنة 3 عروض معدات');
 await user.click(screen.getByRole('button',{name:/افتح خطة المشاركة/}));
 await user.click(screen.getByRole('button',{name:/أضف خطة مقترحة/}));
 await screen.findByText('تحديد هدف المشاركة ومعيار النجاح');
 const boxes=screen.getAllByRole('checkbox');expect(boxes).toHaveLength(9);await user.click(boxes[0]);
 await user.click(screen.getByRole('button',{name:'أضف لقاء'}));
 const contact=within(screen.getByRole('dialog'));
 await user.type(contact.getByLabelText('اسم الشخص'),'أحمد');await user.type(contact.getByLabelText('الجهة'),'مورد التجربة');
 await user.type(contact.getByLabelText('الخطوة التالية'),'طلب عرض شامل');
 await user.click(contact.getByRole('button',{name:'حفظ اللقاء'}));
 await user.click(screen.getByRole('button',{name:'اللقاءات والجهات'}));
 expect(await screen.findByRole('heading',{name:'مورد التجربة'})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'أضف للمهام'}));
 await user.selectOptions(screen.getByLabelText('حالة مورد التجربة'),'offer');
 await user.click(screen.getAllByRole('button',{name:'الأجندة'})[0]);
 await user.click(await screen.findByRole('button',{name:'موعد جديد'}));
 const appt=within(screen.getByRole('dialog'));
 await user.type(appt.getByLabelText('عنوان الموعد'),'اجتماع مراجعة العرض');
 await user.click(appt.getByRole('button',{name:'حفظ'}));
 await user.click(screen.getByRole('button',{name:'النتائج والتقارير'}));
 await user.clear(screen.getByLabelText('المتحقق'));await user.type(screen.getByLabelText('المتحقق'),'2');
 await waitFor(async()=>{const saved=await loadState();expect(saved.state.events[0].actual).toBe(2);expect(saved.state.contacts[0].status).toBe('offer');expect(saved.state.tasks).toHaveLength(10);expect(saved.state.tasks[0].done).toBe(true);expect(saved.state.appointments[0].title).toBe('اجتماع مراجعة العرض');});
 first.unmount();render(<App/>);expect(await screen.findByText('تمت استعادة مشاركاتك')).toBeTruthy();
 expect(screen.getByText('مقارنة 3 عروض معدات')).toBeTruthy();cleanup();
});
