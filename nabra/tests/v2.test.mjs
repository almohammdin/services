import assert from 'node:assert/strict';
import {preservesScope,applyScoped} from '../suggestions.js';
import {rhymeReport,rhymeWords} from '../rhyme.js';
import {scan,inferPoem} from '../prosody.js';
import {validateAudio,audioMime,MAX_AUDIO_BYTES} from '../audio/recorder.js';
const original='هذا صدر أول * هذا عجز أول\nوهذا صدر ثان * وهذا عجز ثان';
const replacement='هذا صدر أول * هذا عجز أول\nوهذا صدر ثان * وهذا عجز بديل';
assert(preservesScope(original,replacement,'1-1'));
assert(!preservesScope(original,replacement.replace('صدر أول','صدر جديد'),'1-1'));
assert(!preservesScope(original,replacement,'0-1'));
assert(!preservesScope(original,'شطر واحد','all'));
assert.equal(applyScoped(original,replacement,'1-1'),replacement);
assert.throws(()=>applyScoped(original,replacement,'0-1'));
assert.equal(rhymeReport('صدر * تمردها\nصدر * يباغتها').groups,2);
assert.equal(rhymeReport('صدر * شهود\nصدر * سكود').groups,1);
assert(rhymeWords('شهود').includes('وعود'));
assert(rhymeWords('تمردها').includes('يصدها'));
assert.equal(scan('قَلْبٌ','pause').pattern,'100');
assert.equal(scan('قَلْبًا','pause').pattern,'1010');
assert.equal(scan('حَيَاةٌ','pause').pattern,scan('حَيَاهْ','pause').pattern);
assert.equal(inferPoem('قَلَمٌ').plausible,false);
assert.equal(audioMime({name:'recording.m4a',type:''}),'audio/mp4');
assert.equal(audioMime({type:'audio/webm;codecs=opus'}),'audio/webm');
assert.throws(()=>validateAudio({size:0,type:'audio/wav'}));
assert.throws(()=>validateAudio({size:MAX_AUDIO_BYTES+1,type:'audio/wav'}));
assert.throws(()=>validateAudio({size:10,type:'text/plain',name:'x.txt'}));
validateAudio({size:100,type:'audio/wav'});
console.log('PASS: selected shatr immutability, rhyme endings, pause/tanwin, prose rejection, audio bounds');
