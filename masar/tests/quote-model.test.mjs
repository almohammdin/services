import assert from 'node:assert/strict';
import {isIssued,fingerprint,preserveIssuedContent,renameClientQuotes,buildMigrationPlan} from '../quote-model.js';
const sent={id:'quote-a',seriesId:'series-a',version:1,client:'Old name',clientId:'client-a',status:'تم إرسال العرض',sentAt:'2026-11-01',scope:'Original scope',amount:45000};
const draft={...sent,id:'quote-b',status:'لم يقدم بعد',sentAt:''};
const renamed=renameClientQuotes([sent,draft],'client-a','Old name','New name');
assert.equal(renamed[0].client,'Old name');
assert.equal(renamed[1].client,'New name');
assert.equal(renamed[0].clientId,'client-a');
assert.equal(sent.client,'Old name');
const admin=preserveIssuedContent(sent,{...sent,scope:'Changed',amount:1,status:'مقبول',collectedAmount:45000,expertise:'Injected'});
assert.equal(admin.scope,'Original scope');
assert.equal(admin.amount,45000);
assert.equal(admin.status,'مقبول');
assert.equal(admin.collectedAmount,45000);
assert.equal(admin.expertise,undefined);
assert.equal(isIssued(admin),true);
assert.equal(fingerprint({...sent,updatedAtIso:'a'}),fingerprint({...sent,updatedAtIso:'b'}));
const snapshot={pricingTool_v1:{quotes:[sent,draft],deletedQuoteIds:['quote-b'],currentQuoteId:sent.id},pricingClients_v1:{clients:[{id:'client-a',name:'New name'}]},authorityMatrices_v1:{matrices:{'client-a':{revision:2,matrixJson:'{}'}}}};
const before=JSON.stringify(snapshot),plan=buildMigrationPlan('test-user',snapshot);
assert.equal(plan.documents.length,3);
assert.equal(plan.documents[0].data.id,'quote-a');
assert.equal(plan.documents[0].data.version,1);
assert.equal(plan.currentQuoteId,sent.id);
assert.equal(plan.sourceRetained,true);
assert.equal(JSON.stringify(snapshot),before);
assert.throws(()=>buildMigrationPlan('test-user',{pricingTool_v1:{quotes:[sent,sent]}}),/Duplicate/);
assert.throws(()=>buildMigrationPlan('test-user',{pricingClients_v1:{clients:[{name:'No ID'}]}}),/Missing/);
console.log('PASS: issued snapshots, renaming, admin updates, fingerprints, migration mapping and validation');
